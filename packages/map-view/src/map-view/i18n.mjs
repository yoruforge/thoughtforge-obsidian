export function resolveMapViewLocale(value = "ja") {
  const normalized = typeof value === "string" ? value.toLowerCase() : "en";
  return normalized.startsWith("ja") ? "ja" : "en";
}

export function createMapViewI18n(locale = "ja") {
  const resolved = resolveMapViewLocale(locale);
  return {
    ...THOUGHTFORGE_WEBVIEW_I18N.en,
    ...THOUGHTFORGE_WEBVIEW_I18N[resolved]
  };
}

export function getMapViewDocumentTitle(locale = "ja") {
  return createMapViewI18n(locale)["app.documentTitle"];
}
